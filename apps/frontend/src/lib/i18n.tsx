const resources: Record<Language, Record<TranslationKey, string>> = { bg, en };

export function translate(
  language: Language,
  key: TranslationKey,
  values?: Record<string, string | number>
): string {
  let message: string = resources[language][key];
  for (const [name, replacement] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, String(replacement));
  }
  return message;
}

interface LanguageContextValue {
  readonly language: Language;
  readonly setLanguage: (language: Language) => void;
  readonly t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: Readonly<{ children: ReactNode }>) {
  const [language, setLanguage] = useState<Language>("bg");
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, values) => translate(language, key, values)
    }),
    [language]
  );
  return createElement(LanguageContext.Provider, { value }, children);
}

export function useI18n(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useI18n must be used inside LanguageProvider");
  return value;
}
